"""Render grounded sections into a Word document, saved atomically and verified by reopening it.

Only text crosses the LLM boundary; the .docx is built here, locally, with python-docx.
"""

import logging
import os
import re
import tempfile
import unicodedata
import uuid
from collections.abc import Callable, Sequence
from datetime import date
from pathlib import Path

from docx import Document
from docx.document import Document as DocxDocument
from docx.opc.exceptions import PackageNotFoundError
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor
from docx.table import _Cell

from app.schemas import Analysis, Assumption, Item, Section, Table

logger = logging.getLogger(__name__)

DOCUMENT_NAME_PATTERN = re.compile(r"^[0-9a-f]{32}-[a-z0-9-]{1,50}\.docx$")
ASSUMPTIONS_HEADING = "Assumptions"

_SLUG_MAX_CHARS = 50
_ACCENT = RGBColor(0x0F, 0x76, 0x6E)
_ACCENT_HEX = "0F766E"
_HEADER_TEXT = RGBColor(0xFF, 0xFF, 0xFF)
_MUTED = RGBColor(0x59, 0x59, 0x59)
_BODY_FONT = "Calibri"
_BODY_SIZE = Pt(11)
_EMPTY_CELL = "—"
_FOOTER_TEXT = "Generated by the Autonomous Document Agent"
_PROPOSAL_LEGEND = (
    "Items marked Proposed, Recommended, Potential or Illustrative are suggestions or possibilities, "
    "not agreed decisions or confirmed facts."
)
_NO_ASSUMPTIONS = "No planning assumptions were needed; all content is based on the request."

ColumnGetter = Callable[[Item], str]


class RenderError(Exception):
    """The document could not be written or failed verification; no link may be returned."""


class DocxRenderer:
    """Pipeline renderer: builds, saves and verifies a document, returning its safe file name."""

    def __init__(self, output_dir: Path) -> None:
        self._output_dir = output_dir

    def __call__(self, analysis: Analysis, sections: Sequence[Section]) -> str:
        title = analysis.title or "Document"
        name = document_name(title)
        document = build_document(analysis, sections)
        try:
            self._output_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise RenderError(f"Could not create the output folder: {exc}") from exc
        _save_verified(document, self._output_dir / name, title, expected_headings=len(sections) + 1)
        logger.info("Rendered %s (%d sections)", name, len(sections))
        return name


def document_name(title: str) -> str:
    """Unique, filesystem-safe name: 32 hex chars + ASCII slug of the title."""
    ascii_title = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_title.lower()).strip("-")[:_SLUG_MAX_CHARS].strip("-")
    return f"{uuid.uuid4().hex}-{slug or 'document'}.docx"


def is_safe_document_name(name: str) -> bool:
    """True only for names this module generates, so paths like '../x' can never be served."""
    return DOCUMENT_NAME_PATTERN.fullmatch(name) is not None


# --------------------------------------------------------------------------- building


def build_document(analysis: Analysis, sections: Sequence[Section]) -> DocxDocument:
    """Title, subtitle, optional proposal legend, one heading per section, then Assumptions."""
    document = Document()
    _apply_base_styles(document)

    document.add_heading(analysis.title or "Document", level=0)
    _add_muted(document, f"{(analysis.document_type or 'document').capitalize()} · "
                         f"Prepared {date.today():%d %B %Y}")
    if any(item.kind == "proposal" for section in sections for item in _all_items(section)):
        _add_muted(document, _PROPOSAL_LEGEND)

    for section in sections:
        _add_section(document, section)
    _add_assumptions(document, analysis.assumptions)

    document.sections[0].footer.paragraphs[0].text = _FOOTER_TEXT
    return document


def _apply_base_styles(document: DocxDocument) -> None:
    normal = document.styles["Normal"]
    normal.font.name = _BODY_FONT
    normal.font.size = _BODY_SIZE
    for style_name in ("Title", "Heading 1"):
        document.styles[style_name].font.color.rgb = _ACCENT


def _add_section(document: DocxDocument, section: Section) -> None:
    document.add_heading(section.heading, level=1)
    for paragraph in section.paragraphs:
        document.add_paragraph(paragraph)
    for item in section.items:
        _add_item(document, item)
    if section.table is not None and section.table.rows:
        _add_table(document, section.table)
    if section.missing_source_note:
        _add_muted(document, section.missing_source_note, italic=True)


def _add_item(document: DocxDocument, item: Item) -> None:
    paragraph = document.add_paragraph(style="List Bullet")
    basis = _basis(item)
    if basis:
        tag = paragraph.add_run(f"{basis}: ")
        tag.bold = True
        tag.font.color.rgb = _ACCENT
    paragraph.add_run(item.text)
    details = "; ".join(
        f"{label}: {value}"
        for label, value in (("Owner", item.owner), ("Due", item.due), ("Value", _value(item)))
        if value
    )
    if details:
        detail_run = paragraph.add_run(f" — {details}")
        detail_run.font.color.rgb = _MUTED


def _add_table(document: DocxDocument, table: Table) -> None:
    columns = _table_columns(table)
    word_table = document.add_table(rows=1, cols=len(columns))
    word_table.style = "Table Grid"
    for cell, (header, _) in zip(word_table.rows[0].cells, columns):
        _set_header_cell(cell, header)
    for row in table.rows:
        cells = word_table.add_row().cells
        for cell, (_, getter) in zip(cells, columns):
            cell.text = getter(row)
    document.add_paragraph()


def _table_columns(table: Table) -> list[tuple[str, ColumnGetter]]:
    """Main text column, then owner/due/value when any row uses them, then Basis if any row is a proposal."""
    columns: list[tuple[str, ColumnGetter]] = [
        (_header(table.columns.text, "text", "Item"), lambda item: item.text)
    ]
    fields: tuple[tuple[str, str, ColumnGetter], ...] = (
        ("owner", "Owner", lambda item: item.owner),
        ("due", "Due", lambda item: item.due),
        ("value", "Value", _value),
    )
    for field_name, default_header, field in fields:
        if any(field(row) for row in table.rows):
            header = _header(getattr(table.columns, field_name), field_name, default_header)
            columns.append((header, lambda item, field=field: field(item) or _EMPTY_CELL))
    if any(row.kind == "proposal" for row in table.rows):
        columns.append(("Basis", lambda item: _basis(item) or "Recorded"))
    return columns


def _value(item: Item) -> str | None:
    """The value field, hidden when it only repeats the owner (e.g. "Owner: Abhinav (Project Lead)")."""
    if item.value and item.owner and item.owner.casefold() in item.value.casefold():
        return None
    return item.value


def _header(label: str | None, field_name: str, default: str) -> str:
    """The model's column label, unless it is missing or just echoes the field name (e.g. "owner")."""
    if not label or label.strip().casefold() == field_name:
        return default
    return label


def _set_header_cell(cell: _Cell, text: str) -> None:
    cell.text = ""
    run = cell.paragraphs[0].add_run(text)
    run.bold = True
    run.font.color.rgb = _HEADER_TEXT
    shading = OxmlElement("w:shd")
    shading.set(qn("w:val"), "clear")
    shading.set(qn("w:color"), "auto")
    shading.set(qn("w:fill"), _ACCENT_HEX)
    cell._tc.get_or_add_tcPr().append(shading)


def _add_assumptions(document: DocxDocument, assumptions: Sequence[Assumption]) -> None:
    document.add_heading(ASSUMPTIONS_HEADING, level=1)
    if not assumptions:
        _add_muted(document, _NO_ASSUMPTIONS, italic=True)
        return
    for assumption in assumptions:
        paragraph = document.add_paragraph(style="List Bullet")
        paragraph.add_run(f"Assumption {assumption.id}: ").bold = True
        paragraph.add_run(assumption.statement)
        paragraph.add_run(f" — {assumption.rationale}").font.color.rgb = _MUTED


def _add_muted(document: DocxDocument, text: str, italic: bool = False) -> None:
    run = document.add_paragraph().add_run(text)
    run.italic = italic
    run.font.color.rgb = _MUTED


def _basis(item: Item) -> str | None:
    """Visible label for proposals ("Proposed", "Assumption A1", ...); None for records."""
    if item.kind != "proposal":
        return None
    parts = [part for part in (item.label, item.assumption_id and f"Assumption {item.assumption_id}") if part]
    return " / ".join(parts) or None


def _all_items(section: Section) -> list[Item]:
    return [*section.items, *(section.table.rows if section.table else [])]


# --------------------------------------------------------------------------- saving


def _save_verified(document: DocxDocument, path: Path, title: str, expected_headings: int) -> None:
    """Save to a temp file in the same folder, verify it, then atomically move it into place."""
    try:
        handle, temp_name = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
        os.close(handle)
    except OSError as exc:
        raise RenderError(f"Could not create a temporary file: {exc}") from exc
    temp_path = Path(temp_name)
    try:
        document.save(temp_path)
        _verify(temp_path, title, expected_headings)
        os.replace(temp_path, path)
    except OSError as exc:
        raise RenderError(f"Could not write the document: {exc}") from exc
    finally:
        temp_path.unlink(missing_ok=True)


def _verify(path: Path, title: str, expected_headings: int) -> None:
    """Reopen the saved file and check its title and section headings."""
    try:
        reopened = Document(str(path))
    except PackageNotFoundError as exc:
        raise RenderError("The saved document could not be reopened.") from exc
    paragraphs = reopened.paragraphs
    if not paragraphs or paragraphs[0].style.name != "Title" or paragraphs[0].text != title:
        raise RenderError("The saved document has no matching title.")
    headings = [p.text for p in paragraphs if p.style.name.startswith("Heading")]
    if len(headings) != expected_headings or headings[-1] != ASSUMPTIONS_HEADING:
        raise RenderError(
            f"The saved document has {len(headings)} headings; expected {expected_headings}."
        )
